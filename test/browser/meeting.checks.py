checks=[]
def evaluate(expression):
    value=js('JSON.stringify('+expression+')',session_id=sid)
    return json.loads(value) if value is not None else None
def body():return js('document.body.innerText',session_id=sid)
def expect(condition,name):
    if not condition:raise AssertionError(name+'\n'+str(body()))
    checks.append(name)
def wait_expression(expression,name):
    deadline=time.monotonic()+5
    while time.monotonic()<deadline:
        cdp('Page.setWebLifecycleState',session_id=sid,state='active')
        if evaluate('Boolean('+expression+')'):expect(True,name);return
        time.sleep(.05)
    expect(False,name)
def wait_text(text,name):wait_expression('document.body.innerText.includes('+json.dumps(text)+')',name)
def click_css(selector):
    js('document.querySelector('+json.dumps(selector)+').click()',session_id=sid)
    cdp('Page.setWebLifecycleState',session_id=sid,state='active');time.sleep(.15)
def click_text(label):
    target='Array.from(document.querySelectorAll("button")).find(e=>e.textContent.trim()==='+json.dumps(label)+' && e.checkVisibility())'
    wait_expression('Boolean('+target+' && !('+target+').disabled)','control exists: '+label)
    js(target+'.click()',session_id=sid)
    cdp('Page.setWebLifecycleState',session_id=sid,state='active');time.sleep(.2)
def fill(label,value,element='textarea'):
    selector=element+'[aria-label="'+label+'"]'
    node='document.querySelector('+json.dumps(selector)+')'
    prototype='HTMLTextAreaElement' if element=='textarea' else 'HTMLInputElement'
    js('Object.getOwnPropertyDescriptor('+prototype+'.prototype,"value").set.call('+node+','+json.dumps(value)+');'+node+'.dispatchEvent(new Event("input",{bubbles:true}))',session_id=sid)
    cdp('Page.setWebLifecycleState',session_id=sid,state='active');time.sleep(.15)
def field(label):return evaluate('document.querySelector('+json.dumps('textarea[aria-label="'+label+'"]')+').value')
