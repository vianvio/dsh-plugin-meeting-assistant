/**
 * 会议助手**宿主半**的诊断日志。
 *
 * 它原先住在插件入口（`index.ts`）里，于是宿主半的每个文件都 import 入口——而入口是有副作用的
 * 模块：模块级会写一条"宿主半模块已加载"、并挂一个 20 秒的看门狗（"apply 还没跑 = inject 没满足"）。
 * 代价是**只 import 宿主半也会执行入口的模块级语句**，而且那条看门狗后来真的会补一条
 * `level:error` 的假故障进共享日志——那份日志会被导出成操作者看的诊断报告，报告里于是多出一条
 * 不存在的 inject 故障，排查的人照着它去追一个没有发生的加载失败。
 *
 * 日志实例是**共享的**（客户端半通过 `diag.adopt` 把它的日志并进同一份，报告要的是两半合并的
 * 一条时间线），所以共享本身不是问题；归属错了才是。这里就是那个归属：一个叶子模块，
 * 谁都可以 import，谁都不会因此执行别人的模块级语句。
 */
import {sharedLog} from '../shared/diag.js';

